USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

USE DATABASE SNOWFLAKE_DB;
USE SCHEMA GOLD_DATAMART;

TRUNCATE TABLE GOLD_DATAMART.DIM_CUSTOMER;

INSERT INTO GOLD_DATAMART.DIM_CUSTOMER(CUSTOMER_ID, FULL_NAME, EMAIL, PHONE, CITY, STATE)
SELECT
    CUSTOMER_ID,
    FIRST_NAME || ' ' || LAST_NAME AS FULL_NAME,
    EMAIL,
    PHONE, 
    CITY,
    STATE
FROM SILVER_TRANSFORMED.CUSTOMERS;
TRUNCATE TABLE GOLD_DATAMART.DIM_PRODUCT;
INSERT INTO GOLD_DATAMART.DIM_PRODUCT(PRODUCT_ID, PRODUCT_NAME, CATEGORY, RETAIL_PRICE)
SELECT
    PRODUCT_ID, PRODUCT_NAME, CATEGORY, RETAIL_PRICE
    FROM SILVER_TRANSFORMED.PRODUCTS;

TRUNCATE TABLE GOLD_DATAMART.DIM_STORE;
INSERT INTO GOLD_DATAMART.DIM_STORE(STORE_ID, STORE_NAME, CITY, STATE)
SELECT
    STORE_ID, STORE_NAME, CITY, STATE 
    FROM SILVER_TRANSFORMED.STORES;
TRUNCATE TABLE GOLD_DATAMART.DIM_DATE;

INSERT INTO GOLD_DATAMART.DIM_DATE (DATE_KEY, FULL_DATE, DAY_OF_WEEK, MONTH_NUM, QUARTER, YEAR)
SELECT 
    TO_CHAR(d.date_val, 'YYYYMMDD')::INT AS DATE_KEY,
    d.date_val AS FULL_DATE,
    DAYNAME(d.date_val) AS DAY_OF_WEEK,
    MONTH(d.date_val) AS MONTH_NUM,
    QUARTER(d.date_val) AS QUARTER,
    YEAR(d.date_val) AS YEAR
FROM (
    SELECT DATEADD(day, SEQ4(), '2026-10-01'::DATE) AS date_val
    FROM TABLE(GENERATOR(ROWCOUNT => 31))
) d;
-- STAR SCHEMA
truncate table GOLD_DATAMART.FACT_SALES;
INSERT INTO GOLD_DATAMART.FACT_SALES( ORDER_ID, ORDER_ITEM_ID, DATE_KEY, CUSTOMER_KEY, PRODUCT_KEY, STORE_KEY, QUANTITY, UNIT_PRICE, STATUS)
    SELECT 
    o.ORDER_ID,
    o.ORDER_ITEM_ID,
    TO_CHAR(o.ORDER_DATE, 'YYYYMMDD')::INT AS DATE_KEY,
    dc.CUSTOMER_KEY,
    dp.PRODUCT_KEY,
    ds.STORE_KEY,
    o.QUANTITY,
    o.UNIT_PRICE,
    o.STATUS
FROM SILVER_TRANSFORMED.ORDERS o
JOIN GOLD_DATAMART.DIM_CUSTOMER dc ON o.CUSTOMER_ID = dc.CUSTOMER_ID
JOIN GOLD_DATAMART.DIM_PRODUCT dp ON o.PRODUCT_ID = dp.PRODUCT_ID
JOIN GOLD_DATAMART.DIM_STORE ds ON o.STORE_ID = ds.STORE_ID;
    -- STAR SCHEMA
    SELECT 'DIM_CUSTOMER' AS ENTITY, COUNT(*) AS ROW_COUNT FROM GOLD_DATAMART.DIM_CUSTOMER
    UNION ALL
    SELECT 'DM_PRODUCT', COUNT(*) FROM GOLD_DATAMART.DIM_PRODUCT
    UNION ALL
    SELECT 'DIM_STORE', COUNT(*) FROM  GOLD_DATAMART.DIM_STORE
    UNION ALL
    SELECT 'DIM_DATE', COUNT(*) FROM GOLD_DATAMART.DIM_DATE
    UNION ALL
    SELECT 'FACT_SALES', COUNT(*) FROM GOLD_DATAMART.FACT_SALES;

    SELECT COUNT(*) AS total_fact_rows FROM GOLD_DATAMART.FACT_SALES;