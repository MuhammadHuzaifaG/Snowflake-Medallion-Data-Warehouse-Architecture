USE ROLE ACCOUNTADMIN;
-- DATABASE
CREATE DATABASE IF NOT EXISTS SNOWFLAKE_DB
    COMMENT = 'DATA WAREHOUSE PORTFOLIO PROJECT';
USE DATABASE SNOWFLAKE_DB;
-- SCHEMAS
CREATE SCHEMA IF NOT EXISTS BRONZE_LANDING
    COMMENT = 'RAW, UNDELIVERED INGESTION LAYER';
CREATE SCHEMA IF NOT EXISTS SILVER_TRANSFORMED
    COMMENT = 'CLEANED, TYPED & DEDUPLICATED LAYER';
CREATE SCHEMA IF NOT EXISTS GOLD_DATAMART
    COMMENT = 'STAR SCHEMA OPTIMIZED FOR BI & ANALYTICS';
-- BRONZE LAYER
CREATE OR REPLACE TABLE BRONZE_LANDING.RAW_ORDERS_STREAM (
    PAYLOAD VARIANT,
    METADATA_FILENAME VARCHAR,
    METADATA_FILE_ROW_NUMBER INT,
    METADATA_LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
-- SILVER LAYER 
CREATE OR REPLACE TABLE SILVER_TRANSFORMED.CUSTOMERS (
    CUSTOMER_ID VARCHAR(32) NOT NULL,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(30),
    ADDRESS VARCHAR(255),
    CITY VARCHAR(50),
    STATE VARCHAR(30),
    ZIP_CODE VARCHAR(20),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE OR REPLACE TABLE SILVER_TRANSFORMED.PRODUCTS (
    PRODUCT_ID INT NOT NULL,
    PRODUCT_NAME VARCHAR(100),
    CATEGORY VARCHAR(50),
    RETAIL_PRICE NUMBER(12, 2),
    SUPPLIER_PRICE NUMBER(12, 2),
    SUPPLIER_ID INT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE OR REPLACE TABLE SILVER_TRANSFORMED.STORES (
    STORE_ID VARCHAR(32) NOT NULL,
    STORE_NAME VARCHAR(100),
    ADDRESS VARCHAR(255),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    ZIP_CODE VARCHAR(30),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(30),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE OR REPLACE TABLE SILVER_TRANSFORMED.EMPLOYEES (
    EMPLOYEE_ID INT NOT NULL,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    EMAIL VARCHAR(100),
    JOB_TITLE VARCHAR(50),
    HIRE_DATE DATE,
    MANAGER_ID INT,
    STORE_ID VARCHAR(32),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE OR REPLACE TABLE SILVER_TRANSFORMED.ORDERS (
    ORDER_ID INT NOT NULL,
    ORDER_ITEM_ID INT NOT NULL,
    ORDER_DATE DATE,
    CUSTOMER_ID VARCHAR(32),
    EMPLOYEE_ID INT,
    STORE_ID VARCHAR(32), 
    PRODUCT_ID INT,
    QUANTITY INT,
    UNIT_PRICE NUMBER(12, 2),
    STATUS VARCHAR(10),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
--  GOLD LAYER
-- DIMENSION TABLES
CREATE OR REPLACE TABLE GOLD_DATAMART.DIM_CUSTOMER (
    CUSTOMER_KEY INT AUTOINCREMENT START 1 INCREMENT 1,
    CUSTOMER_ID VARCHAR(32) NOT NULL,
    FULL_NAME VARCHAR(100),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(32),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    CONSTRAINT PK_DIM_CUSTOMER PRIMARY KEY (CUSTOMER_KEY)
);
CREATE OR REPLACE TABLE GOLD_DATAMART.DIM_DATE (
    DATE_KEY INT NOT NULL,
    FULL_DATE DATE NOT NULL,
    DAY_OF_WEEK VARCHAR(10),
    MONTH_NUM INT,
    QUARTER INT,
    YEAR INT,
    CONSTRAINT PK_DIM_DATE PRIMARY KEY (DATE_KEY)
);
CREATE OR REPLACE TABLE GOLD_DATAMART.DIM_PRODUCT (
    PRODUCT_KEY INT AUTOINCREMENT START 1 INCREMENT 1,
    PRODUCT_ID INT NOT NULL,
    PRODUCT_NAME VARCHAR(100),
    CATEGORY VARCHAR(50),
    RETAIL_PRICE NUMBER(12, 2),
    CONSTRAINT PK_DIM_PRODUCT PRIMARY KEY (PRODUCT_KEY)
);
CREATE OR REPLACE TABLE GOLD_DATAMART.DIM_STORE (
    STORE_KEY INT AUTOINCREMENT START 1 INCREMENT 1,
    STORE_ID VARCHAR(32) NOT NULL,
    STORE_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    CONSTRAINT PK_DIM_STORE PRIMARY KEY (STORE_KEY)
);
CREATE OR REPLACE TABLE GOLD_DATAMART.FACT_SALES (
    SALE_ID INT AUTOINCREMENT START 1 INCREMENT 1,
    ORDER_ID INT NOT NULL,
    ORDER_ITEM_ID INT NOT NULL,
    DATE_KEY INT NOT NULL,
    CUSTOMER_KEY INT NOT NULL,
    PRODUCT_KEY INT NOT NULL,
    STORE_KEY INT NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE NUMBER(12, 2) NOT NULL,
    GROSS_REVENUE NUMBER(38, 2) GENERATED ALWAYS AS (QUANTITY * UNIT_PRICE),
    STATUS VARCHAR(10),
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    -- Informational Constraints & Relationships
    CONSTRAINT PK_FACT_SALES PRIMARY KEY (SALE_ID),
    CONSTRAINT FK_SALES_DATE FOREIGN KEY (DATE_KEY) 
        REFERENCES GOLD_DATAMART.DIM_DATE(DATE_KEY),
    CONSTRAINT FK_SALES_CUSTOMER FOREIGN KEY (CUSTOMER_KEY) 
        REFERENCES GOLD_DATAMART.DIM_CUSTOMER(CUSTOMER_KEY),
    CONSTRAINT FK_SALES_PRODUCT FOREIGN KEY (PRODUCT_KEY) 
        REFERENCES GOLD_DATAMART.DIM_PRODUCT(PRODUCT_KEY),
    CONSTRAINT FK_SALES_STORE FOREIGN KEY (STORE_KEY) 
        REFERENCES GOLD_DATAMART.DIM_STORE(STORE_KEY)
)
CLUSTER BY (DATE_KEY, STORE_KEY);